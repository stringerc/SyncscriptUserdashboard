// ── Types ──────────────────────────────────────────────────────────

export type SynthesisStage =
  | 'idle'
  | 'parsing_spec'
  | 'generating_code'
  | 'validating_epistemic'
  | 'sandbox_testing'
  | 'installing'
  | 'complete'
  | 'failed';

export type ToolCategory =
  | 'file_ops'
  | 'code_analysis'
  | 'data_transform'
  | 'api_integration'
  | 'system_query'
  | 'workflow_automation'
  | 'custom';

export interface ToolSpec {
  name: string;
  description: string;
  category: ToolCategory;
  inputSchema: Record<string, any>; // JSON Schema
  outputSchema: Record<string, any>; // JSON Schema
  sideEffects?: string[]; // e.g., ['writes_file', 'executes_command', 'network_request']
  requiresApproval?: boolean;
  examples?: Array<{ input: any; output: any; description: string }>;
  constraints?: string[]; // Natural language constraints
}

export interface GeneratedTool {
  id: string;
  spec: ToolSpec;
  code: string;
  testCode: string;
  typesCode: string;
  documentation: string;
  createdAt: number;
  epistemicTags: string[];
}

export interface ValidationResult {
  passed: boolean;
  collapseGateScore: number;
  actionGateScore: number;
  coherenceScore: number;
  semanticScore: number;
  errors: string[];
  warnings: string[];
  epistemicConfidence: number;
}

export interface SandboxResult {
  passed: boolean;
  stdout: string;
  stderr: string;
  exitCode: number;
  durationMs: number;
  memoryMB: number;
  testResults: Array<{ name: string; passed: boolean; durationMs: number; error?: string }>;
}

export interface SynthesisRecord {
  id: string;
  spec: ToolSpec;
  generatedTool: GeneratedTool | null;
  validation: ValidationResult | null;
  sandbox: SandboxResult | null;
  installed: boolean;
  installPath: string | null;
  status: SynthesisStage;
  error: string | null;
  startedAt: number;
  completedAt: number | null;
  durationMs: number | null;
}

